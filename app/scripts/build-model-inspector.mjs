import {rolldown} from 'rolldown';
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
const build=await rolldown({input:fileURLToPath(new URL('src/lib/model-inspector-runtime.ts',root))});
try{
 const {output}=await build.generate({format:'iife',minify:true});
 if(output.length!==1||output[0].type!=='chunk')throw new Error('Expected one offline model runtime.');
 const notice=await readFile(new URL('node_modules/three/LICENSE',root),'utf8');
 const code=`/* Three.js license:\n${notice}\n*/\n${output[0].code}`;
 await writeFile(new URL('src/generated/model-inspector-runtime.ts',root),`// Generated by scripts/build-model-inspector.mjs. Do not edit.\nexport const modelInspectorRuntime=${JSON.stringify(code)};\n`);
}finally{await build.close();}
